"""Action-only actual-NSE-role referee for the Cartan projector connection gauge."""
import numpy as np
from exp58_resolved_cartan_material_metric import waves, random_divfree
from exp59_role_space_cartan_gauge import orthonormalize, matrices


def main():
    rng=np.random.default_rng(65082026)
    n=8; ks=waves(n)
    cov=fixed=tangent=reset=kelvin=0.0
    signal=0.0
    for _ in range(120):
        V=random_divfree(rng,n,ks,2.0)
        W=orthonormalize([random_divfree(rng,n,ks,3.0) for _ in range(5)])
        K,S=matrices(V,W,ks)
        # Actual physical role matrices from resolved NSE obey K*=-K, S*=S.
        X=rng.normal(size=(5,5)); O,_=np.linalg.qr(X)
        P=O[:,:2]@O[:,:2].T
        c=rng.normal(size=5)
        L=K+S

        comm=K@P-P@K
        direct=float(c@P@L@c + .5*c@comm@c)
        strain=float(c@P@S@c)
        cov=max(cov,abs(direct-strain)/(1+abs(direct)+abs(strain)))

        # Fixed role: G=-[K,P] reconstructs visible K flux exactly.
        G=-comm
        fixed_rhs=float(c@P@S@c + .5*c@G@c)
        fixed_direct=float(c@P@L@c)
        fixed=max(fixed,abs(fixed_rhs-fixed_direct)/(1+abs(fixed_rhs)+abs(fixed_direct)))

        # Arbitrary tangent selector mismatch generated by another skew connection J.
        Y=rng.normal(size=(5,5)); J=Y-Y.T
        G2=J@P-P@J
        Pdot=comm+G2
        lhs=float(c@P@L@c + .5*c@Pdot@c)
        rhs=float(c@P@S@c + .5*c@G2@c)
        tangent=max(tangent,abs(lhs-rhs)/(1+abs(lhs)+abs(rhs)),
                    np.linalg.norm(P@Pdot@P)/(1+np.linalg.norm(Pdot)),
                    np.linalg.norm((np.eye(5)-P)@Pdot@(np.eye(5)-P))/(1+np.linalg.norm(Pdot)))
        signal=max(signal,np.linalg.norm(comm),np.linalg.norm(G2))

        # Finite reset identity.
        Z=rng.normal(size=(5,5)); O2,_=np.linalg.qr(Z); P2=O2[:,:3]@O2[:,:3].T
        jump=.5*float(c@(P2-P)@c)
        direct_jump=.5*float(c@P2@c-c@P@c)
        reset=max(reset,abs(jump-direct_jump)/(1+abs(jump)+abs(direct_jump)))

        # Kelvin orientation-complete selector commutes with pure orientation connection.
        m=4
        diag=(rng.random(m)>.5).astype(float)
        M=np.diag(diag)
        R=rng.normal(size=(3,3)); Om=R-R.T
        Pk=np.kron(M,np.eye(3)); Kori=np.kron(np.eye(m),Om)
        kelvin=max(kelvin,np.linalg.norm(Kori@Pk-Pk@Kori)/(1+np.linalg.norm(Kori)))

    print(f"worst connection-comoving selected-energy residual: {cov:.3e}")
    print(f"worst fixed-role K-flux reconstruction residual: {fixed:.3e}")
    print(f"worst general projector-defect/tangent residual: {tangent:.3e}")
    print(f"worst finite projector-reset residual: {reset:.3e}")
    print(f"worst Kelvin orientation-selector commutator residual: {kelvin:.3e}")
    print(f"maximum sampled physical selector-interface signal: {signal:.3e}")
    assert cov<3e-12
    assert fixed<3e-12
    assert tangent<5e-12
    assert reset<3e-12
    assert kelvin<2e-14
    assert signal>1e-4
    print("PASS: fixed K relink and moving-role connection are exact projector gauges of one Cartan sector")


if __name__=='__main__': main()
